// Helpers

export function getClinic(id: string): Clinic {
  return CLINICS.find((c) => c.id === id) ?? CLINICS[0];
}

export function formatReviews(n: number): string {
  if (n % 10 === 1 && n % 100 !== 11) return `${n} отзыв`;
  if ([2, 3, 4].includes(n % 10) && ![12, 13, 14].includes(n % 100)) return `${n} отзыва`;
  return `${n} отзывов`;
}

export function initials(name: string): string {
  const parts = name.split(" ");
  return (parts[0]?.[0] ?? "") + (parts[1]?.[0] ?? "");
}

// Детерминированный мягкий цвет аватара из имени
export function avatarHue(name: string): number {
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) % 360;
  return h;
}

export function formatPhoneInput(value: string): string {
  // Маска +7 (XXX) XXX-XX-XX
  let digits = value.replace(/\D/g, "");
  if (digits.startsWith("8")) digits = "7" + digits.slice(1);
  if (!digits.startsWith("7")) digits = "7" + digits;
  digits = digits.slice(0, 11);
  const a = digits.slice(1, 4);
  const b = digits.slice(4, 7);
  const c = digits.slice(7, 9);
  const d = digits.slice(9, 11);
  let out = "+7";
  if (a) out += ` (${a}`;
  if (a.length === 3) out += ")";
  if (b) out += ` ${b}`;
  if (c) out += `-${c}`;
  if (d) out += `-${d}`;
  return out;
}

export function isValidPhone(value: string): boolean {
  return value.replace(/\D/g, "").length === 11;
}
